#!/usr/bin/env python3
"""Write src/lean_pkg/data/upgrade-breaking.yaml from the upgrade records docs/upgrades/*.yaml.

scripts/upgrade-breaking.py            rewrite the data file (also run by `make docs`)
scripts/upgrade-breaking.py --check    exit 1, writing nothing, when the committed file differs

The data file lists every record entry with `breaking: true` (version, id, pr, kind, area), so an
installed lean-pkg, which carries no docs/, can name the breaking changes between the lean-pkg that wrote
a receipt and the one running (`status NAME`, `doctor --package NAME`; lean_pkg/producer_skew.py). The
in-progress (provisional) record is listed like the released ones; the reader filters by version.
tests/test_producer_skew.py fails when the committed file is not this script's output, so a pull
request that adds or changes a breaking entry regenerates it (RELEASING.md, "The breaking-entries file").
`release-version.py --rename` (cut-release step 2b) rewrites it after renaming the record.
Needs PyYAML (a lean-pkg dependency).
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
RECORD_DIR = "docs/upgrades"
DATA_FILE = "src/lean_pkg/data/upgrade-breaking.yaml"
SCHEMA = "lean-pkg-upgrade-breaking/1"
FIELDS = ("version", "id", "pr", "kind", "area")
_VERSION = re.compile(r"^(\d+)\.(\d+)\.(\d+)$")

HEADER = f"""\
# Generated by scripts/upgrade-breaking.py from {RECORD_DIR}/*.yaml; do not edit (`make docs` rewrites it).
# Every upgrade-record entry with breaking: true, oldest release first. `lean-pkg status NAME` and
# `lean-pkg doctor --package NAME` read it to name the breaking changes between the lean-pkg that wrote a
# package's receipts (their `producer.lean_pkg`) and the running one (lean_pkg/producer_skew.py).
# The in-progress record (a provisional name) is included; the reader filters by version.
"""


def _key(version: str) -> tuple[int, int, int]:
    m = _VERSION.fullmatch(version)
    if not m:
        raise ValueError(f"version {version!r} is not X.Y.Z")
    return tuple(int(g) for g in m.groups())


def entries(root: Path = ROOT) -> list[dict]:
    """The breaking entries of every record under root/docs/upgrades, oldest version first, record order
    within a version. Raises ValueError on a record this cannot read (the record checks name it too)."""
    out = []
    for path in sorted((root / RECORD_DIR).glob("*.yaml")):
        doc = yaml.safe_load(path.read_text(encoding="utf-8"))
        if not isinstance(doc, dict):
            raise ValueError(f"{path.name}: not a mapping")
        version = str(doc.get("version"))
        _key(version)
        for i, e in enumerate(doc.get("changes") or []):
            if not isinstance(e, dict):
                raise ValueError(f"{path.name}: changes[{i}] is not a mapping")
            if e.get("breaking") is True:
                missing = [f for f in FIELDS[1:] if f not in e]
                if missing:
                    raise ValueError(f"{path.name}: changes[{i}] lacks {', '.join(missing)}")
                out.append({"version": version, "id": str(e["id"]), "pr": int(e["pr"]),
                            "kind": str(e["kind"]), "area": str(e["area"])})
    return sorted(out, key=lambda e: _key(e["version"]))   # stable: record order kept within a version


def render(root: Path = ROOT) -> str:
    rows = [("  - {" + ", ".join(f"{f}: {json.dumps(e[f])}" for f in FIELDS) + "}") for e in entries(root)]
    return HEADER + f"schema: {SCHEMA}\n" + ("entries:\n" + "\n".join(rows) + "\n" if rows else "entries: []\n")


def write(root: Path = ROOT) -> bool:
    """Rewrite root/DATA_FILE; True when its bytes changed."""
    path = root / DATA_FILE
    text = render(root)
    old = path.read_text(encoding="utf-8") if path.is_file() else None
    if old != text:
        path.write_text(text, encoding="utf-8")
    return old != text


def main(argv: list[str]) -> int:
    if argv not in ([], ["--check"]):
        print("usage: scripts/upgrade-breaking.py [--check]", file=sys.stderr)
        return 2
    try:
        text = render()
    except (OSError, ValueError, yaml.YAMLError) as e:
        print(f"upgrade-breaking: {e}", file=sys.stderr)
        return 1
    path = ROOT / DATA_FILE
    if argv == ["--check"]:
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            print(f"upgrade-breaking: {DATA_FILE} is stale; run python3 scripts/upgrade-breaking.py "
                  f"(or make docs)", file=sys.stderr)
            return 1
        print(f"upgrade-breaking: {DATA_FILE} is current")
        return 0
    changed = write()
    print(f"upgrade-breaking: {DATA_FILE} {'rewritten' if changed else 'unchanged'}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
