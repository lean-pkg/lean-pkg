# lean-pkg site check -- proposal 0012, phase 1: an offline check of a package's documentation site
"""`lean-pkg site check [NAME] [--dir DIR] [--repo DIR] [--no-registry] [--json]`.

Proposal 0012 (docs/proposals/0012-site-standard.md) gives a package's site one standard lean-pkg can check,
keep current and create. Phase 1 is this read-only check; `site render` (phase 2) and `site init` (phase 3)
come later, so the checks that only a render can satisfy are reported as warnings here, never as failures:
the hand-written counts, the opt-in key, a hand-written page under a generated name.

The site directory (default `docs`, relative to the repository root) is one of three kinds:

- `static`: `DIR/.nojekyll`; GitHub Pages serves the committed files as they are;
- `mkdocs`: `mkdocs.yml` at the repository root whose `docs_dir` is DIR (MkDocs' default is `docs`);
- `jekyll`: anything else GitHub Pages builds from DIR (`_config.yml`, or an index page).

With NAME the registry record supplies the package's checkout (or `--repo DIR`), its visibility (the noindex
check) and the generated pages to compare (`page --site`); without NAME, or with `--no-registry`, the
repository is the current directory and those checks are reported as n/a. Nothing is written.
"""

from __future__ import annotations

import os
import pathlib
import re

import yaml

from . import core
from . import html_blocks

KINDS = ("jekyll", "mkdocs", "static")
OPT_IN_KEY = "lean_pkg_site"
STATIC_OPT_IN = "lean-pkg-site.yaml"
GENERATED_PAGES = ("verification.md", "coverage.md")
GENERATED_MARK = "<!-- Generated by `lean-pkg page"
PAGE_SUFFIXES = (".md", ".markdown", ".html", ".htm")
ASSET_SUFFIXES = (".css", ".js", ".mjs", ".map", ".png", ".jpg", ".jpeg", ".gif", ".svg", ".ico", ".webp",
                  ".avif", ".woff", ".woff2", ".ttf", ".otf", ".eot", ".pdf", ".mp4", ".webm", ".txt", ".xml",
                  ".json", ".bib", ".cff")
# files whose bytes a build reads: a copy served beside the site goes stale and is not what the receipts bind.
# A served file is a copy when its path below the site directory ends with the path of a tracked file outside
# it (docs/source/claims.yaml and claims.yaml), or the other way round; a Lean example kept only in the site
# is not a copy.
BUILD_INPUT_NAMES = ("claims.yaml", "coverage.yaml", "lake-manifest.json", "lean-toolchain", "lean-pkg-binding.yaml",
                     "formalization.yaml")
BUILD_INPUT_SUFFIXES = (".lean", ".olean", ".ilean")
NOINDEX = re.compile(r"<meta\s+[^>]*name\s*=\s*[\"']robots[\"'][^>]*content\s*=\s*[\"'][^\"']*noindex", re.I)
NOINDEX_REV = re.compile(r"<meta\s+[^>]*content\s*=\s*[\"'][^\"']*noindex[^\"']*[\"'][^>]*name\s*=\s*[\"']robots",
                         re.I)
MATHJAX = re.compile(r"mathjax", re.I)
MATH_MD = re.compile(r"^\s*```\s*latex\b|\$\$|\\\(|\\\[", re.M)
MATH_HTML = re.compile(r"language-latex|\$\$|\\\(|\\\[")
_FENCE = re.compile(r"^\s*(```|~~~)")

# hand-written quantities that drift (proposal 0012, "Generated blocks"; the list is its open question 2)
_COUNT_NOUNS = r"(?:claims?|scopes?|theorems?|lemmas?|results?|declarations?|modules?|definitions?)"
_COUNT_ADJ = (r"(?:(?:verified|conditional|excluded|reusable|public|internal|numbered|main|formalized|proved|"
              r"owned|leaf|reusable)\s+){0,2}")
_NUM = r"\d+(?:,\d{3})*"
COUNT = re.compile(rf"\b{_NUM}\s+(?:of\s+(?:the\s+)?{_NUM}\s+)?{_COUNT_ADJ}{_COUNT_NOUNS}\b", re.I)
VERSION = re.compile(r"\b(?:lean-pkg|source api|api)\s+v?\d+\.\d+\.\d+\b", re.I)
COMMIT = re.compile(r"\b(?:commit|source|pinned at|pin)\s+`?[0-9a-f]{7,40}`?\b")
EXEMPT = re.compile(r"<!--\s*lean-pkg:site:exempt\s+([^>]*?)\s*-->")
BLOCK_OPEN = re.compile(r"<!--\s*lean-pkg:(?:site:(?!end\b|exempt\b)[\w-]+|page:begin)\s*-->")
BLOCK_CLOSE = re.compile(r"<!--\s*lean-pkg:(?:site:end|page:end)\s*-->")


# --------------------------------------------------------------------------
# the site directory


def _read(p: pathlib.Path) -> str:
    try:
        return p.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""


def _yaml(p: pathlib.Path) -> dict:
    """A YAML mapping, or {} for a missing or unreadable file. mkdocs.yml may use `!!python/name` tags, which
    safe_load refuses; those documents are read with unknown tags kept as plain values."""
    if not p.is_file():
        return {}

    class _Loader(yaml.SafeLoader):
        pass

    _Loader.add_multi_constructor("", lambda loader, suffix, node: None)
    try:
        doc = yaml.load(_read(p), Loader=_Loader)   # noqa: S506 -- SafeLoader subclass, unknown tags -> None
    except yaml.YAMLError:
        return {}
    return doc if isinstance(doc, dict) else {}


def tracked(repo: pathlib.Path, rel: str) -> list[str]:
    """Paths tracked under rel (repository-relative, POSIX): what a branch deployment serves."""
    p = core.git(repo, "ls-files", "-z", "--", rel)
    if p.returncode != 0:
        return []
    return sorted(x for x in p.stdout.split("\0") if x)


def detect(repo: pathlib.Path, rel: str) -> dict:
    """{kind: jekyll|mkdocs|static|None, opt_in, mkdocs: the parsed mkdocs.yml or {}}."""
    d = repo / rel
    mk = _yaml(repo / "mkdocs.yml")
    mk_dir = str(mk.get("docs_dir") or "docs").strip("/") if (repo / "mkdocs.yml").is_file() else None
    if (d / ".nojekyll").exists():
        kind = "static"
        opt = _yaml(d / STATIC_OPT_IN).get(OPT_IN_KEY) == 1
    elif mk_dir is not None and mk_dir == rel.strip("/"):
        kind = "mkdocs"
        opt = (mk.get("extra") or {}).get(OPT_IN_KEY) == 1 if isinstance(mk.get("extra"), dict) else False
    elif d.is_dir() and ((d / "_config.yml").is_file() or any((d / f"index{s}").is_file() for s in PAGE_SUFFIXES)):
        kind = "jekyll"
        opt = _yaml(d / "_config.yml").get(OPT_IN_KEY) == 1
    else:
        kind, opt = None, False
    return {"kind": kind, "opt_in": bool(opt), "mkdocs": mk}


def served(kind: str, files: list[str], rel: str) -> list[str]:
    """The tracked files the host publishes: Jekyll leaves out names starting with `_` or `.` (below DIR);
    MkDocs and a static site publish every file of DIR (MkDocs renders the Markdown)."""
    out = []
    for f in files:
        sub = pathlib.PurePosixPath(f).relative_to(rel) if rel not in ("", ".") else pathlib.PurePosixPath(f)
        if kind == "jekyll" and any(part.startswith(("_", ".")) for part in sub.parts):
            continue
        if kind != "jekyll" and sub.name in (".nojekyll", STATIC_OPT_IN, ".gitignore"):
            continue
        out.append(f)
    return out


def _is_generated(text: str) -> bool:
    return GENERATED_MARK in text[:400]


# --------------------------------------------------------------------------
# the checks


def _links(kind: str, d: pathlib.Path, mk: dict, generated: list[str]) -> list[str]:
    """Generated pages the landing page (or MkDocs' nav) does not link to."""
    if not generated:
        return []
    if kind == "mkdocs":
        nav = mk.get("nav")
        if nav is None:
            return []                                   # no nav: MkDocs lists every page
        flat = repr(nav)
        return [g for g in generated if g not in flat]
    index = next((d / f"index{s}" for s in PAGE_SUFFIXES if (d / f"index{s}").is_file()), None)
    # the landing page and, for Jekyll, the layouts and includes that carry the site's navigation; a link
    # may be relative, absolute or built by Liquid ({{ '/verification.html' | relative_url }})
    texts = [_read(index)] if index else []
    if kind == "jekyll":
        texts += [_read(f) for f in sorted([*d.glob("_layouts/*.html"), *d.glob("_includes/*.html")])]
    text = "\n".join(texts)
    out = []
    for g in generated:
        stem = g.rsplit(".", 1)[0]
        if not re.search(rf"(?:^|[\s\"'(/=])(?:\./)?{re.escape(stem)}(?:\.md|\.html|/)?(?=[\"')#|\s]|$)", text, re.M):
            out.append(g)
    return out


def _counts(path: str, text: str) -> tuple[list[dict], list[dict]]:
    """(findings, exemptions): quantities written by hand outside generated blocks and code fences. An exempt
    comment covers its own line and the next one."""
    found, exempt, inside, fenced, cover = [], [], False, False, -1
    for i, line in enumerate(text.splitlines(), 1):
        if _FENCE.match(line):
            fenced = not fenced
            continue
        if BLOCK_OPEN.search(line):
            inside = True
        if BLOCK_CLOSE.search(line):
            inside = False
            continue
        if inside or fenced:
            continue
        m = EXEMPT.search(line)
        if m:
            exempt.append({"file": path, "line": i, "source": m.group(1)})
            cover = i + 1
        for rx, what in ((COUNT, "count"), (VERSION, "version"), (COMMIT, "commit")):
            for hit in rx.finditer(line):
                if i <= cover:
                    continue
                found.append({"file": path, "line": i, "kind": what, "text": hit.group(0)[:80]})
    return found, exempt


def _cff_abstract(repo: pathlib.Path) -> str:
    a = _yaml(repo / "CITATION.cff").get("abstract")
    return a if isinstance(a, str) else ""


def _head_texts(kind: str, repo: pathlib.Path, d: pathlib.Path, mk: dict, pages: list[pathlib.Path]
                ) -> list[tuple[str, str]]:
    """[(path, text)] of the files that make the pages' head: a Jekyll site's layouts and includes, MkDocs'
    custom_dir templates and extra_javascript, or each static page itself."""
    if kind == "jekyll":
        files = sorted([*d.glob("_layouts/*.html"), *d.glob("_includes/*.html")])
    elif kind == "mkdocs":
        theme = mk.get("theme") if isinstance(mk.get("theme"), dict) else {}
        cdir = theme.get("custom_dir")
        files = sorted((repo / cdir).rglob("*.html")) if isinstance(cdir, str) and (repo / cdir).is_dir() else []
        extra = mk.get("extra_javascript") or []
        js = " ".join(str(x.get("path", "") if isinstance(x, dict) else x) for x in extra)
        return [(str(f.relative_to(repo)), _read(f)) for f in files] + [("mkdocs.yml extra_javascript", js)]
    else:
        files = [p for p in pages if p.suffix in (".html", ".htm")]
    return [(str(f.relative_to(repo)), _read(f)) for f in files]


def check(repo: pathlib.Path, rel: str = "docs", pkg: dict | None = None, *, allow_private: bool = False) -> dict:
    """The site check payload (see the module docstring and docs/site.md). pkg is the registry record, or None
    for the offline form."""
    rel = rel.strip("/") or "."
    d = repo / rel
    info = detect(repo, rel)
    kind, mk = info["kind"], info["mkdocs"]
    out: dict = {"ok": True, "dir": rel, "kind": kind, "opt_in": info["opt_in"], "registry": pkg is not None,
                 "generated": [], "stale": [], "links": {"missing": []}, "html_blocks": [], "counts": [],
                 "exemptions": [], "math": {"pages_with_math": 0, "mathjax": None, "problems": []},
                 "noindex": {"expected": None, "present": None, "files": []},
                 "served": {"files": 0, "build_input_copies": [], "unclassified": []},
                 "shadowing_index_html": False,
                 "binding": {"docs_descendant": None, "reason": "site render is proposal 0012 phase 2"},
                 "snapshot": {"source": None, "stale": None, "reason": "site render is proposal 0012 phase 2"},
                 "problems": [], "warnings": []}
    if kind is None:
        out["warnings"].append(f"no site: {rel}/ holds no index page, no _config.yml, no .nojekyll, and no "
                               f"mkdocs.yml names it; nothing to check")
        return out
    problems, warnings = out["problems"], out["warnings"]
    if not info["opt_in"]:
        where = {"jekyll": f"{rel}/_config.yml", "mkdocs": "mkdocs.yml under extra:",
                 "static": f"{rel}/{STATIC_OPT_IN}"}[kind]
        warnings.append(f"not opted in: add `{OPT_IN_KEY}: 1` to {where} (proposal 0012)")
    files = tracked(repo, rel)
    pub = served(kind, files, rel)
    out["served"]["files"] = len(pub)
    pages = [repo / f for f in pub if f.lower().endswith(PAGE_SUFFIXES)]

    # generated pages, and hand-written pages under their names
    for g in GENERATED_PAGES:
        p = d / g
        if p.is_file():
            if _is_generated(_read(p)):
                out["generated"].append(g)
            else:
                warnings.append(f"{rel}/{g} is hand-written under a name `page --site` writes; site render "
                                f"(phase 2) will not overwrite it: rename it or replace it with the generated page")

    # current: the generated pages against what `page --site` writes now (needs the record)
    if out["generated"] and pkg is not None and pkg.get("name"):
        try:
            from . import page as page_mod
            outputs, _facts, _w = page_mod.render_all(pkg, repo, allow_private)
            baseline, _f, _w2 = page_mod.render_all(pkg, repo, allow_private, advisories=False)
            targets = [(f"{rel}/{g}", d / g, g) for g in out["generated"]]
            for shown, status, problem in page_mod.site_status(targets, outputs, baseline):
                if status != "current":
                    out["stale"].append(shown)
                    problems.append(problem or f"{shown}: {status}")
        except (core.Fail, core.UsageError) as e:
            warnings.append(f"current: not checked: {e}")
    elif out["generated"]:
        warnings.append("current: not checked without the registry record (`site check NAME`)")

    # links
    out["links"]["missing"] = _links(kind, d, mk, out["generated"])
    for g in out["links"]["missing"]:
        problems.append(f"links: the landing page does not link to {rel}/{g}"
                        + (" (mkdocs.yml nav)" if kind == "mkdocs" else ""))

    # Markdown inside HTML blocks (a renderer's rule; a static site serves its Markdown as text)
    if kind != "static":
        for p in pages:
            if p.suffix not in (".md", ".markdown"):
                continue
            for line, tag, md in html_blocks.findings(_read(p)):
                rp = str(p.relative_to(repo))
                out["html_blocks"].append({"file": rp, "line": line, "tag": tag, "markdown": md[:80]})
                problems.append(f"html block: {rp}:{line}: <{tag}> without markdown=\"1\" holds Markdown that "
                                f"would be published as text: {md[:60]}")

    # hand-written counts, versions and commits (warnings in phase 1: render writes the blocks in phase 2)
    sources = [(str(p.relative_to(repo)), _read(p)) for p in pages if not _is_generated(_read(p))]
    for extra in ("README.md", "llms.txt"):
        if (repo / extra).is_file():
            sources.append((extra, _read(repo / extra)))
    abstract = _cff_abstract(repo)
    if abstract:
        sources.append(("CITATION.cff abstract", abstract))
    for path, text in sources:
        found, exempt = _counts(path, text)
        out["counts"] += found
        out["exemptions"] += exempt
    if out["counts"]:
        warnings.append(f"counts: {len(out['counts'])} count(s), version(s) or commit(s) written by hand outside "
                        f"generated blocks; they drift when the evidence changes (proposal 0012, generated "
                        f"blocks); mark one `<!-- lean-pkg:site:exempt SOURCE -->` to keep it")

    # mathematics
    with_math = [p for p in pages if (MATH_HTML if p.suffix in (".html", ".htm") else MATH_MD).search(_read(p))]
    out["math"]["pages_with_math"] = len(with_math)
    heads = _head_texts(kind, repo, d, mk, pages)
    if kind == "static":
        lacking = [str(p.relative_to(repo)) for p in with_math if not MATHJAX.search(_read(p))]
        out["math"]["mathjax"] = not lacking
        for f in lacking:
            warnings.append(f"math: {f} has mathematics and loads no MathJax (a static page renders it as text)")
    else:
        have = any(MATHJAX.search(t) for _, t in heads) or any(MATHJAX.search(_read(p)) for p in with_math)
        out["math"]["mathjax"] = have
        if kind == "mkdocs" and with_math and "arithmatex" not in repr(mk.get("markdown_extensions")):
            out["math"]["problems"].append("mkdocs.yml does not enable pymdownx.arithmatex")
        if with_math and not have:
            out["math"]["problems"].append(f"{len(with_math)} page(s) have mathematics and the head loads no "
                                           f"MathJax ({'layouts and includes' if kind == 'jekyll' else 'theme custom_dir or extra_javascript'})")
        problems += [f"math: {m}" for m in out["math"]["problems"]]

    # noindex: in the head the pages actually use
    if kind == "static":
        html_pages = [p for p in pages if p.suffix in (".html", ".htm")]
        with_tag = [str(p.relative_to(repo)) for p in html_pages if _noindex(_read(p))]
        present = bool(html_pages) and len(with_tag) == len(html_pages)
        partial = bool(with_tag) and not present
    else:
        with_tag = [f for f, t in heads if _noindex(t)]
        present, partial = bool(with_tag), False
    out["noindex"].update(present=present, files=with_tag)
    if pkg is not None:
        expected = str(pkg.get("visibility") or "").lower() == "private"
        out["noindex"]["expected"] = expected
        if expected and not present:
            problems.append("noindex: the package is private and "
                            + ("some served pages lack" if partial else "the site's head has no")
                            + " <meta name=\"robots\" content=\"noindex\">")
        if not expected and with_tag:
            problems.append(f"noindex: the package is public and the site still says noindex ({', '.join(with_tag[:3])})")
    else:
        warnings.append("noindex: not checked without the registry record (the package's visibility)")

    # served files
    outside = [f for f in tracked(repo, ".") if not f.startswith(rel.rstrip("/") + "/")] if rel != "." else []
    for f in pub:
        name = pathlib.PurePosixPath(f).name
        low = name.lower()
        if name in BUILD_INPUT_NAMES or low.endswith(BUILD_INPUT_SUFFIXES) or low.startswith("lakefile."):
            sub = str(pathlib.PurePosixPath(f).relative_to(rel)) if rel != "." else f
            if any(sub == o or sub.endswith("/" + o) or o.endswith("/" + sub) for o in outside):
                out["served"]["build_input_copies"].append(f)
        elif not low.endswith(PAGE_SUFFIXES + ASSET_SUFFIXES):
            out["served"]["unclassified"].append(f)
    for f in out["served"]["build_input_copies"]:
        problems.append(f"served: {f} is a copy of a build input the site publishes; it goes stale: link the "
                        f"file at a commit (`blob/<commit>/...`) instead")
    if out["served"]["unclassified"]:
        warnings.append(f"served: {len(out['served']['unclassified'])} published file(s) that are neither pages "
                        f"nor assets: {', '.join(out['served']['unclassified'][:5])}")
    if kind == "static":
        warnings.append(f"served: {rel}/.nojekyll publishes every committed file of {rel}/ as it is: Jekyll's "
                        f"`exclude` and `_`-prefixed names do not apply")

    # the landing page
    if kind == "jekyll" and (d / "index.html").is_file() and any((d / f"index{s}").is_file()
                                                               for s in (".md", ".markdown")):
        out["shadowing_index_html"] = True
        problems.append(f"landing page: {rel}/index.html takes precedence over {rel}/index.md on GitHub Pages")

    out["ok"] = not problems
    return out


def _noindex(text: str) -> bool:
    return bool(NOINDEX.search(text) or NOINDEX_REV.search(text))


