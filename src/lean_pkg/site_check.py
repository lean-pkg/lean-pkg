# the command


def _lines(name: str | None, res: dict) -> list[str]:
    who = name or "(no registry)"
    if res["kind"] is None:
        return [f"site check: {who}: OK; no site in {res['dir']}/ (nothing to check)"]
    verdict = (f"site check: {who}: {'OK' if res['ok'] else 'FAIL'}; {res['kind']} site in {res['dir']}/, "
               f"{'opted in' if res['opt_in'] else 'not opted in'}; {len(res['problems'])} problem(s), "
               f"{len(res['warnings'])} warning(s)")
    out = [verdict]
    out += [f"  ✗ {p}" for p in res["problems"]]
    out += [f"  ! {w}" for w in res["warnings"]]
    for c in res["counts"][:20]:
        out.append(f"    {c['file']}:{c['line']}: {c['kind']}: {c['text']}")
    if len(res["counts"]) > 20:
        out.append(f"    ... {len(res['counts']) - 20} more (--json lists them all)")
    if len(out) > 12:
        out.append(verdict)
    return out


def run_check(args) -> int:
    name = getattr(args, "name", None)
    offline = bool(getattr(args, "no_registry", False)) or name is None
    if getattr(args, "repo", None) and offline:
        raise core.UsageError("site check --repo DIR needs NAME and the registry; without them the repository "
                              "is the current directory")
    pkg = None
    if offline:
        top = core.git(pathlib.Path.cwd(), "rev-parse", "--show-toplevel")
        if top.returncode != 0:
            raise core.UsageError("site check without NAME (or with --no-registry) runs in a git checkout: "
                                  "the current directory is not inside one")
        repo = pathlib.Path(top.stdout.strip())
    else:
        from . import coverage as cov
        from . import gate as gate_mod
        reg = core.load_registry(core.registry_path(args))
        if getattr(args, "repo", None):
            reg, _view = gate_mod.repo_override(reg, name, args.repo)
        pkg, repo = cov.package_checkout(reg, name)
    rel = os.path.normpath(args.dir).strip("/")
    if rel.startswith("..") or os.path.isabs(args.dir):
        raise core.UsageError(f"site check --dir {args.dir}: must be a directory inside the repository")
    res = check(repo, rel, pkg, allow_private=bool(getattr(args, "allow_private_manuscript", False)))
    res["name"] = name
    if getattr(args, "json_out", False):
        core.print_json(res)
    else:
        print("\n".join(_lines(name, res)))
    return 0 if res["ok"] else 1


def cmd_site(args) -> int:
    fn = getattr(args, "site_fn", None)
    if fn is None:
        raise core.UsageError("site needs an action: check")
    return fn(args)


def add_parsers(sub, add_json) -> None:
    s = sub.add_parser("site", help="a package's documentation site (proposal 0012): `site check` reads it "
                                    "offline (Jekyll, MkDocs or a static site served as committed)")
    add_json(s)
    s.set_defaults(fn=cmd_site, site_fn=None)
    ssub = s.add_subparsers(dest="site_cmd")
    c = ssub.add_parser("check", help="read-only: check the site in DIR (default docs): generated pages current "
                                      "and linked, Markdown inside HTML blocks, mathematics, the noindex while "
                                      "private, the files it serves, a shadowing index.html; hand-written counts "
                                      "are warnings; exit 0/1")
    c.add_argument("name", nargs="?", default=None)
    c.add_argument("--dir", default="docs", metavar="DIR",
                   help="the site directory, relative to the repository root (default: docs)")
    c.add_argument("--repo", default=None, metavar="DIR",
                   help="with NAME: check this checkout of the package instead of the registered local_path")
    c.add_argument("--no-registry", action="store_true",
                   help="read no registry record: the repository is the current directory; the checks that "
                        "need the record (generated pages current, the noindex against the visibility) are "
                        "reported as not checked (the form a package's CI runs)")
    c.add_argument("--allow-private-manuscript", action="store_true",
                   help="as for page: render the generated pages of a package whose manuscript is unposted")
    add_json(c)
    c.set_defaults(fn=cmd_site, site_fn=run_check)
