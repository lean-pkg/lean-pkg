#!/usr/bin/env python3
"""wiki: Markdown status page rendering."""

from __future__ import annotations

from .conftest import set_lease


def test_wiki_renders_table_banner_lease_and_refs(lp, env, capsys):
    set_lease(env, "alpha", agent="vera", workspace="w3", hours_ago=1, ttl=24)
    rc = lp.main(["--registry", str(env.registry), "wiki"])
    assert rc == 0
    out = capsys.readouterr().out
    assert "title: Lean Verification Status" in out
    assert "type: lean-verification" in out
    assert "machine-generated by `lean-pkg wiki`" in out
    assert "do not hand-edit" in out
    assert "## Packages" in out
    assert "| alpha |" in out and "| beta |" in out
    assert "vera@w3" in out
    assert "## Active leases" in out and "until" in out
    assert "## References" in out
    assert "DESIGN.md" in out
    assert "`lean-pkg llms`" in out


def test_wiki_no_adoption_ledger_line(lp, env, capsys):
    rc = lp.main(["--registry", str(env.registry), "wiki"])
    assert rc == 0
    assert "no adoption ledger found" in capsys.readouterr().out


def test_wiki_no_leases_line(lp, env, capsys):
    rc = lp.main(["--registry", str(env.registry), "wiki"])
    assert rc == 0
    assert "- none" in capsys.readouterr().out


def test_wiki_adoptions_table_and_summary(lp, env, candidates_file, capsys):
    rc = lp.main(["--registry", str(env.registry), "wiki"])
    assert rc == 0
    out = capsys.readouterr().out
    assert "| package | upstream_pin | consumers | license |" in out
    assert "| cool-lib | abc123def456 | alpha | Apache-2.0 |" in out
    assert "1 adopted" in out and "1 watch-only" in out and "0 rejected" in out
    # watch-only entries are counted, not tabulated
    assert "| watch-lib |" not in out


def test_wiki_candidates_override(lp, env, candidates_file, tmp_path, capsys):
    other = tmp_path / "elsewhere.yaml"
    other.write_text(candidates_file.read_text())
    candidates_file.unlink()  # default path now absent; override must win
    rc = lp.main(["--registry", str(env.registry), "wiki",
                  "--candidates", str(other)])
    assert rc == 0
    assert "| cool-lib |" in capsys.readouterr().out


def test_wiki_out_writes_file(lp, env, tmp_path, capsys):
    out_p = tmp_path / "content" / "lean-verification" / "index.md"
    rc = lp.main(["--registry", str(env.registry), "wiki", "--out", str(out_p)])
    assert rc == 0
    assert out_p.is_file()
    text = out_p.read_text()
    assert "## Packages" in text and "| beta |" in text
    assert "wrote" in capsys.readouterr().out
