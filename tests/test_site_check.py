#!/usr/bin/env python3
"""`lean-pkg site check` (proposal 0012, phase 1): an offline check of a package's site of each kind (Jekyll,
MkDocs, static served as committed). Problems fail it; what only `site render` (phase 2) can fix is a warning."""

from __future__ import annotations

import json
import subprocess
from pathlib import Path

from lean_pkg import site_check as sc

from .conftest import _git
from .test_page import prepare, run

LAYOUT = """<!doctype html><html><head>
<meta name="robots" content="noindex, nofollow, noarchive">
<script src="https://cdn.jsdelivr.net/npm/mathjax@3.2.2/es5/tex-chtml.js"></script>
</head><body>{{ content }}</body></html>
"""
GENERATED = "# Verification\n\n<!-- Generated by `lean-pkg page beta` (site output) from coverage.yaml -->\n"


def repo(tmp_path: Path, files: dict[str, str]) -> Path:
    r = tmp_path / "r"
    r.mkdir()
    subprocess.run(["git", "init", "-q", str(r)], check=True)
    for rel, text in files.items():
        p = r / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
    _git(r, "add", "-A")
    _git(r, "commit", "-q", "-m", "site")
    return r


def test_no_site_is_ok_and_says_so(tmp_path):
    res = sc.check(repo(tmp_path, {"README.md": "# x\n"}))
    assert res["ok"] and res["kind"] is None and "no site" in res["warnings"][0]


def test_kinds_and_opt_in(tmp_path):
    r = repo(tmp_path, {"docs/_config.yml": "lean_pkg_site: 1\n", "docs/index.md": "# x\n"})
    assert sc.detect(r, "docs")["kind"] == "jekyll" and sc.detect(r, "docs")["opt_in"]
    (r / "docs" / ".nojekyll").write_text("")
    assert sc.detect(r, "docs") == {"kind": "static", "opt_in": False, "mkdocs": {}}
    (r / "docs" / ".nojekyll").unlink()
    (r / "mkdocs.yml").write_text("site_name: x\nextra:\n  lean_pkg_site: 1\n")   # docs_dir defaults to docs
    info = sc.detect(r, "docs")
    assert info["kind"] == "mkdocs" and info["opt_in"]
    (r / "mkdocs.yml").write_text("site_name: x\ndocs_dir: site-src\n")
    assert sc.detect(r, "docs")["kind"] == "jekyll"                                 # mkdocs names another dir


def test_a_clean_private_jekyll_site_passes(tmp_path):
    r = repo(tmp_path, {
        "docs/_config.yml": "theme: null\nlean_pkg_site: 1\n", "docs/_layouts/default.html": LAYOUT,
        "docs/index.md": "# Pkg\n\n[Verification](verification.md) and [coverage](coverage.html).\n",
        "docs/verification.md": GENERATED + "\n```latex\nx^2\n```\n", "docs/coverage.md": GENERATED})
    res = sc.check(r, "docs", {"visibility": "private"})
    assert res["ok"], res["problems"]
    assert res["generated"] == ["verification.md", "coverage.md"] and res["links"]["missing"] == []
    assert res["noindex"] == {"expected": True, "present": True, "files": ["docs/_layouts/default.html"]}
    assert res["math"]["mathjax"] is True and res["math"]["pages_with_math"] == 1


def test_jekyll_problems(tmp_path):
    r = repo(tmp_path, {
        "docs/index.md": "# Pkg\n\nSee coverage.\n", "docs/index.html": "<html></html>\n",
        "docs/verification.md": GENERATED, "docs/what.md": "<details>\n| a | b |\n</details>\n\n$$x$$\n",
        "claims.yaml": "claims: []\n", "docs/source/claims.yaml": "claims: []\n",
        "docs/examples/Example.lean": "theorem t : True := trivial\n"})
    res = sc.check(r, "docs", {"visibility": "public"})
    text = "\n".join(res["problems"])
    assert not res["ok"]
    assert res["links"]["missing"] == ["verification.md"]
    assert res["html_blocks"][0]["file"] == "docs/what.md" and res["html_blocks"][0]["tag"] == "details"
    assert res["shadowing_index_html"] is True and "index.html takes precedence" in text
    assert res["served"]["build_input_copies"] == ["docs/source/claims.yaml"]   # an example only here: no copy
    assert "head loads no MathJax" in text
    assert res["noindex"]["expected"] is False and res["noindex"]["present"] is False
    assert any("not opted in" in w for w in res["warnings"])


def test_noindex_against_visibility(tmp_path):
    files = {"docs/_config.yml": "theme: null\n", "docs/_layouts/default.html": LAYOUT, "docs/index.md": "# x\n"}
    r = repo(tmp_path, files)
    assert sc.check(r, "docs", {"visibility": "private"})["ok"]
    res = sc.check(r, "docs", {"visibility": "public"})
    assert not res["ok"] and "public and the site still says noindex" in "\n".join(res["problems"])
    offline = sc.check(r, "docs", None)
    assert offline["ok"] and offline["noindex"]["expected"] is None
    assert any("noindex: not checked" in w for w in offline["warnings"])


def test_static_site_every_page_needs_the_tag(tmp_path):
    page = '<html><head><meta name="robots" content="noindex"></head><body>\\(x\\)</body></html>\n'
    r = repo(tmp_path, {"docs/.nojekyll": "", "docs/index.html": page, "docs/api.html": "<html>\\(x\\)</html>\n",
                        "docs/api.md": "<details>\n| a |\n</details>\n"})
    res = sc.check(r, "docs", {"visibility": "private"})
    assert res["kind"] == "static" and not res["ok"]
    assert "some served pages lack" in "\n".join(res["problems"])
    assert res["html_blocks"] == []                       # a static site serves its Markdown as text
    assert any("loads no MathJax" in w for w in res["warnings"])       # reported, not failed
    assert any(".nojekyll publishes every committed file" in w for w in res["warnings"])


def test_mkdocs_nav_and_math(tmp_path):
    r = repo(tmp_path, {
        "mkdocs.yml": "site_name: x\nnav:\n  - index.md\n  - verification.md\ntheme:\n  name: material\n"
                      "  custom_dir: overrides\n",
        "overrides/main.html": LAYOUT, "docs/index.md": "# x\n", "docs/verification.md": GENERATED,
        "docs/coverage.md": GENERATED, "docs/math.md": "$$x$$\n"})
    res = sc.check(r, "docs", {"visibility": "private"})
    text = "\n".join(res["problems"])
    assert res["kind"] == "mkdocs" and res["links"]["missing"] == ["coverage.md"]
    assert "does not enable pymdownx.arithmatex" in text
    assert res["noindex"]["present"] is True and res["noindex"]["files"] == ["overrides/main.html"]


def test_counts_skip_blocks_fences_and_exemptions():
    text = "\n".join([
        "We prove 47 verified scopes.",                                    # 1: found
        "<!-- lean-pkg:site:exempt the coverage map -->",                  # 2: exempts 2 and 3
        "30 of 30 numbered results.",                                     # 3: exempt
        "<!-- lean-pkg:site:status -->", "12 claims", "<!-- lean-pkg:site:end -->",   # 4-6: generated
        "```", "lean-pkg 0.27.0 output: 3 theorems", "```",               # 7-9: fenced
        "Built with lean-pkg 0.27.0 at commit `9cafe12`.",               # 10: version and commit
        "Theorem 3, 0, claims and 2026 are not counts."])                 # 11: nothing
    found, exempt = sc._counts("p.md", text)
    assert [(f["line"], f["kind"]) for f in found] == [(1, "count"), (10, "version"), (10, "commit")]
    assert exempt == [{"file": "p.md", "line": 2, "source": "the coverage map"}]


def test_cli_offline_and_usage(lp, tmp_path, capsys, monkeypatch):
    r = repo(tmp_path, {"docs/_config.yml": "theme: null\n", "docs/index.md": "# x\n\n10 theorems.\n"})
    monkeypatch.chdir(r)
    capsys.readouterr()
    assert lp.main(["site", "check", "--no-registry"]) == 0
    out = capsys.readouterr().out.splitlines()
    assert out[0].startswith("site check: (no registry): OK; jekyll site in docs/, not opted in")
    assert lp.main(["--json", "site", "check"]) == 0
    data = json.loads(capsys.readouterr().out)
    assert data["kind"] == "jekyll" and data["counts"][0]["text"] == "10 theorems" and data["registry"] is False
    assert lp.main(["site", "check", "--repo", str(r)]) == 2                   # --repo needs NAME
    assert lp.main(["site", "check", "--dir", "../x"]) == 2


def test_with_the_registry_generated_pages_are_compared(lp, env, capsys):
    prepare(env)
    rc, _out, _err = run(lp, env, capsys, "page", "beta", "--site", str(env.repo_b / "docs"))
    assert rc == 0
    (env.repo_b / "docs" / "index.md").write_text("# beta\n\n[V](verification.md) [C](coverage.md)\n")
    _git(env.repo_b, "add", "docs")
    _git(env.repo_b, "commit", "-q", "-m", "site")
    rc, out, _err = run(lp, env, capsys, "--json", "site", "check", "beta")
    data = json.loads(out)
    assert data["generated"] == ["verification.md", "coverage.md"] and data["stale"] == [], data["problems"]
    assert data["noindex"]["expected"] is True and rc == 1                     # private, and no noindex yet
    v = env.repo_b / "docs" / "verification.md"
    v.write_text(v.read_text() + "edited\n")
    rc, out, _err = run(lp, env, capsys, "--json", "site", "check", "beta")
    assert rc == 1 and json.loads(out)["stale"] == ["docs/verification.md"]
